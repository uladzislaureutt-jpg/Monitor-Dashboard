type I18nValue = string | number;
type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, values?: Record<string, I18nValue>) => string;
  formatLocale: string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function loadLocale(): Locale {
  return localStorage.getItem(STORAGE_KEY) === "be" ? "be" : "ru";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(loadLocale);
  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale;
    document.title = locale === "be" ? "Манітор" : "Монитор";
  }, [locale]);
  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale: setLocaleState,
    formatLocale: locale === "be" ? "be-BY" : "ru-RU",
    t: (key, values) => {
      let text = (locale === "be" ? BE : RU)[key] ?? RU[key];
      if (values) {
        for (const [name, value] of Object.entries(values)) text = text.replaceAll(`{${name}}`, String(value));
      }
      return text;
    },
  }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
